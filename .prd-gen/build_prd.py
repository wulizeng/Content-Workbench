def ea_run(r, size=None, bold=None, color=None, italic=None):
    r.font.name = EA
    rpr = r._element.get_or_add_rPr()
    rf = rpr.find(qn('w:rFonts'))
    if rf is None:
        rf = OxmlElement('w:rFonts'); rpr.append(rf)
    for k in ('w:eastAsia', 'w:ascii', 'w:hAnsi'):
        rf.set(qn(k), EA)
    if size is not None: r.font.size = Pt(size)
    if bold is not None: r.font.bold = bold
    if color is not None: r.font.color.rgb = color
    if italic is not None: r.font.italic = italic

st = doc.styles['Normal']
st.font.name = EA; st.font.size = Pt(10.5)
st.element.rPr.rFonts.set(qn('w:eastAsia'), EA)
st.paragraph_format.space_after = Pt(4)
st.paragraph_format.line_spacing = 1.25
