    hs.font.name = EA; hs.font.size = Pt(sz); hs.font.bold = True
    hs.font.color.rgb = INK if lv > 1 else ACCENT
    hs.element.rPr.rFonts.set(qn('w:eastAsia'), EA)
    hs.paragraph_format.space_before = Pt(12 if lv == 1 else 8)
    hs.paragraph_format.space_after = Pt(6)

