def H(l, t):
    p = doc.add_heading(t, level=l)
    for r in p.runs: ea_run(r)
    return p

def P(t, bold=False, size=10.5, color=None, italic=False):
    p = doc.add_paragraph()
    r = p.add_run(t); ea_run(r, size, bold, color, italic)
    return p

def B(items, size=10.5):
    for it in items:
        p = doc.add_paragraph(style='List Bullet')
        r = p.add_run(it); ea_run(r, size)

def shade(cell, fill):
    tcPr = cell._tc.get_or_add_tcPr()
    sh = OxmlElement('w:shd')
    sh.set(qn('w:val'), 'clear'); sh.set(qn('w:fill'), fill)
    tcPr.append(sh)

def T(heads, rows, widths=None, size=9):
    tb = doc.add_table(rows=1, cols=len(heads))
    tb.style = 'Table Grid'
    tb.alignment = WD_TABLE_ALIGNMENT.CENTER
    tb.autofit = False
    for i, h in enumerate(heads):
        c = tb.rows[0].cells[i]
        c.text = ''
        r = c.paragraphs[0].add_run(h); ea_run(r, size, True, INK)
        shade(c, 'EEF0FF')
    for row in rows:
        cells = tb.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = ''
            for j, ln in enumerate(str(v).split('\n')):
                p = cells[i].paragraphs[0] if j == 0 else cells[i].add_paragraph()
                r = p.add_run(ln); ea_run(r, size)
                p.paragraph_format.space_after = Pt(0)
    if widths:
        for i, w in enumerate(widths):
            for row in tb.rows:
                row.cells[i].width = Inches(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return tb

def FIG(name, cap, w=6.5):
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
